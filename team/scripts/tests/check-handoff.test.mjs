#!/usr/bin/env node
/**
 * check-handoff.test.mjs — handoff 门禁（四锚）测试（T-20261010-052210 门禁扩面反证）
 *
 * 覆盖：
 *   A. 原口径：已登记 running|closed seg ⇒ handoff 必须存在且含四锚；
 *   B. 扩面（新增）：status ∈ {in_progress,in_review} 且 handoff.md **已存在** ⇒ 亦校验四锚
 *      ——拦「绕过 ACL 直跑 spawn、留下手写缺锚 handoff」在 seg 登记**前/后**（登记前由 B 命中）。
 * 隔离：OPENCLAW_TEAM_ROOT = mkdtemp（TASKS_DIR 于模块加载期读取，须先设 env 再 import）。
 * 运行：node --test scripts/tests/check-handoff.test.mjs
 */
import { test as nodeTest, after, beforeEach } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

/** 定位携带 ACL 库的 provider 安装目录（与 archive.test.mjs / check-idem.test.mjs 同口径）。 */
function resolveProviderRoot() {
  const candidates = [
    process.env.OPENCLAW_TASK_OPS_DIR,
    path.join(os.homedir(), '.openclaw', 'team', 'skills', 'task-ops'),
    path.join(os.homedir(), '.openclaw', 'skills', 'task-ops'),
  ].filter(Boolean);
  for (const c of candidates) {
    if (fs.existsSync(path.join(c, 'lib', 'team-paths.mjs'))) return c;
  }
  return null;
}
const PROVIDER = resolveProviderRoot();
const SKIP = PROVIDER
  ? false
  : 'provider ACL library not installed (task-ops is intentionally not vendored); set OPENCLAW_TASK_OPS_DIR to run';
const test = SKIP ? nodeTest.skip : nodeTest;

const ROOT = fs.mkdtempSync(path.join(os.tmpdir(), 'oc-handoff-'));
process.env.OPENCLAW_TEAM_ROOT = ROOT;
const TASKS = path.join(ROOT, 'tasks');
const WS = path.join(ROOT, 'workspace');
fs.mkdirSync(TASKS, { recursive: true });
fs.mkdirSync(WS, { recursive: true });

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CLI = path.join(HERE, '..', 'check-handoff.mjs');
// provider 依赖为**条件动态 import**：缺 provider 时 check-handoff.mjs/lib.mjs 在 import 期即硬红。
let checkHandoff, anchorGaps, ANCHORS;
if (PROVIDER) {
  process.env.OPENCLAW_TASK_OPS_DIR = PROVIDER;
  ({ checkHandoff, anchorGaps, ANCHORS } = await import('../check-handoff.mjs'));
}

after(() => fs.rmSync(ROOT, { recursive: true, force: true }));
beforeEach(() => {
  for (const f of fs.readdirSync(TASKS)) fs.rmSync(path.join(TASKS, f), { recursive: true, force: true });
  fs.rmSync(WS, { recursive: true, force: true });
  fs.mkdirSync(WS, { recursive: true });
});

// 规范 handoff（含全部四锚；与 task.handoff 生成物同结构）
const CANON = [
  '<!-- HANDOFF:v1 (generated by task.handoff; 勿手改) -->',
  '# Handoff — t (T-20260101-000000-x) · seg:seg1',
  '## 任务卡',
  '- Goal: x',
  '## 上段结论（Report 摘要）',
  '（无）',
  '## 讨论/决策（Comments 摘要）',
  '（无）',
  '## state.md',
  '- 路径: /x/state.md',
  '',
].join('\n');
// 手写件：四锚全缺（正文不得字面含任一锚串，否则不算「缺锚」）
const HANDWRITTEN = '# Handoff\n手写件：无规范标记块、无章节、无状态文件引用\n';

const sessionLine = (seg, status = 'running') =>
  `- seg:${seg} · owner:linus · backend:claude · id:11111111-2222-3333-4444-555555555555 · phase:p · status:${status} · pid:${process.pid} · 2026-01-01T00:00:00.000Z`;

function writeCard(id, { status = 'in_progress', segs = [] } = {}) {
  const body = `## Background\nx\n## Acceptance\n- [ ] a\n## Progress\n## Comments\n## Sessions\n${segs.map((s) => sessionLine(s)).join('\n')}\n## Report\n`;
  fs.writeFileSync(path.join(TASKS, `${id}.md`), `---\nid: ${id}\ntitle: ho\nassignee: linus\nstatus: ${status}\nproject: __team__\n---\n${body}`);
}
function writeHandoff(id, content) {
  fs.mkdirSync(path.join(WS, id), { recursive: true });
  fs.writeFileSync(path.join(WS, id, 'handoff.md'), content);
}

test('0. 锚口径自洽：anchorGaps 与 ANCHORS 一致，规范文本零缺失', () => {
  assert.deepEqual(anchorGaps(CANON), []);
  assert.equal(ANCHORS.length, 5);
  assert.equal(anchorGaps(HANDWRITTEN).length, ANCHORS.length);
});

test('1. A 口径：已登记 running seg + 规范 handoff ⇒ 通过', () => {
  const id = 'T-20260101-000001-a';
  writeCard(id, { segs: ['seg1'] });
  writeHandoff(id, CANON);
  const r = checkHandoff();
  assert.equal(r.ok, true, JSON.stringify(r));
  assert.equal(r.failures.length, 0);
});

test('2. A 口径（原行为保留）：已登记 seg + 手写缺锚 ⇒ 报缺锚', () => {
  const id = 'T-20260101-000002-a';
  writeCard(id, { segs: ['seg1'] });
  writeHandoff(id, HANDWRITTEN);
  const r = checkHandoff();
  assert.equal(r.ok, false);
  const f = r.failures.find((x) => x.id === id && x.seg === 'seg1');
  assert.ok(f && f.type === 'anchors', JSON.stringify(r.failures));
  assert.ok(f.missing.includes('HANDOFF:v1'));
});

test('3. A 口径：已登记 seg 但缺 handoff.md ⇒ missing', () => {
  const id = 'T-20260101-000003-a';
  writeCard(id, { segs: ['seg1'] });
  const r = checkHandoff();
  assert.equal(r.ok, false);
  assert.ok(r.failures.some((x) => x.id === id && x.type === 'missing'));
});

test('4. 扩面（红）：in_progress + 手写缺锚 handoff，**无任何 seg 登记** ⇒ 拦（登记前即拦）', () => {
  const id = 'T-20260101-000004-b';
  writeCard(id, { status: 'in_progress', segs: [] }); // Sessions 空 = 直跑 spawn 的典型态
  writeHandoff(id, HANDWRITTEN);
  const r = checkHandoff();
  assert.equal(r.ok, false, `应被扩面拦下，实际 ${JSON.stringify(r)}`);
  const f = r.failures.find((x) => x.id === id);
  assert.ok(f && f.type === 'anchors' && f.status === 'in_progress', JSON.stringify(r.failures));
  assert.ok(f.missing.includes('## 任务卡'));
});

test('5. 扩面（红）：in_review + 缺锚 handoff ⇒ 拦', () => {
  const id = 'T-20260101-000005-b';
  writeCard(id, { status: 'in_review', segs: [] });
  writeHandoff(id, HANDWRITTEN);
  const r = checkHandoff();
  assert.equal(r.ok, false);
  assert.ok(r.failures.some((x) => x.id === id && x.type === 'anchors'));
});

test('6. 扩面（绿）：in_progress + 规范 handoff，无 seg ⇒ 通过', () => {
  const id = 'T-20260101-000006-b';
  writeCard(id, { status: 'in_progress', segs: [] });
  writeHandoff(id, CANON);
  const r = checkHandoff();
  assert.equal(r.ok, true, JSON.stringify(r));
});

test('7. 不误报：in_progress 且**无** handoff.md、无 seg ⇒ 通过（缺失只由 A 口径负责）', () => {
  const id = 'T-20260101-000007-b';
  writeCard(id, { status: 'in_progress', segs: [] });
  const r = checkHandoff();
  assert.equal(r.ok, true, JSON.stringify(r));
});

test('8. 作用域：非在途状态（ready）+ 缺锚 handoff ⇒ 不检查（通过）', () => {
  const id = 'T-20260101-000008-c';
  writeCard(id, { status: 'ready', segs: [] });
  writeHandoff(id, HANDWRITTEN);
  const r = checkHandoff();
  assert.equal(r.ok, true, JSON.stringify(r));
});

test('9. CLI 退出码语义：缺锚 exit 1，规范 exit 0', () => {
  const env = { ...process.env, OPENCLAW_TEAM_ROOT: ROOT };
  const id = 'T-20260101-000009-cli';
  writeCard(id, { status: 'in_progress', segs: [] });
  writeHandoff(id, HANDWRITTEN);

  let code = 0;
  let out = '';
  try {
    out = execFileSync(process.execPath, [CLI], { env, encoding: 'utf8' });
  } catch (e) {
    code = e.status;
    out = String(e.stdout || '');
  }
  assert.equal(code, 1, `缺锚应 exit 1，实际 ${code}；输出 ${out}`);
  assert.match(out, /缺锚/);

  writeHandoff(id, CANON);
  const out2 = execFileSync(process.execPath, [CLI], { env, encoding: 'utf8' });
  assert.match(out2, /handoff 校验通过/);
});
