/**
 * agent-doc-blocks.mjs — `SHARED-RULE` 与 `REDLINES:v1` 标记块的解析/渲染。
 *
 * 为什么单独一层：sync（写）、check（校验）、lint（引用解析）必须用同一套
 * marker 语法。任何一处各自实现，都会在「payload 字节相等」这种硬约束上分叉。
 *
 * 设计要点：
 *   · 围栏感知：``` 代码块里的 marker 是示例，不是真块。
 *   · payload = BEGIN 行之后到 END 行之前的**原样行**（不含两端换行）；比较按字节。
 *   · owner 块由人写；carrier 块由 sync 生成，永不手改。
 *   · 只依赖 node 内置，不 import lib.mjs（后者缺 provider 会硬退出）。
 */
import fs from 'node:fs';
import path from 'node:path';

export const ROLES = ['elon', 'jobs', 'linus', 'turing', 'assistant'];

export const RULE_ID_RE = /^R-[A-Z][A-Z0-9]*-[0-9]+$/;
export const RULE_REF_RE = /(?<![A-Za-z0-9-])R-[A-Z][A-Z0-9]*-[0-9]+(?![0-9A-Za-z-])/g;

const BEGIN_RE = /^<!--\s*BEGIN SHARED-RULE:(\S+)\s+(v\d+)\s+(.*?)\s*-->$/;
const END_RE = /^<!--\s*END SHARED-RULE:(\S+)\s*-->$/;
const RED_BEGIN_RE = /^<!--\s*BEGIN REDLINES:v1\b/;
const RED_END_RE = /^<!--\s*END REDLINES:v1\s*-->/;
const GENERATED_HEADING = '## Shared rules (generated)';
const GENERATED_NOTE = '<!-- generated by team/scripts/sync-shared-rules.mjs; do not hand-edit -->';

export class BlockError extends Error {
  constructor(message, line) {
    super(line ? `${message}（第 ${line} 行）` : message);
    this.line = line;
  }
}

/** 解析 `key=value` 串；`detail=` 可含空格（到下一个 key= 前）。 */
export function parseMeta(text) {
  const out = {};
  for (const part of String(text || '').split(/\s+(?=[A-Za-z][A-Za-z0-9_-]*=)/)) {
    const i = part.indexOf('=');
    if (i < 0) continue;
    const k = part.slice(0, i);
    if (k) out[k] = part.slice(i + 1);
  }
  return out;
}

/** 标记围栏状态：返回每行是否处于 fence 内（含 fence 行本身）。 */
export function fencedLines(lines) {
  const out = new Array(lines.length).fill(false);
  let fence = false;
  for (let i = 0; i < lines.length; i++) {
    if (/^\s*```/.test(lines[i])) { out[i] = true; fence = !fence; }
    else out[i] = fence;
  }
  return out;
}

/** 解析文本中的全部 SHARED-RULE 块（owner 与 carrier 都返回）。 */
export function parseRuleBlocks(text) {
  const lines = String(text).split('\n');
  const fenced = fencedLines(lines);
  const blocks = [];
  for (let i = 0; i < lines.length; i++) {
    if (fenced[i]) continue;
    const m = lines[i].match(BEGIN_RE);
    if (!m) {
      if (END_RE.test(lines[i])) throw new BlockError('SHARED-RULE END 没有对应 BEGIN', i + 1);
      continue;
    }
    const [, id, version, metaText] = m;
    if (!RULE_ID_RE.test(id)) throw new BlockError(`非法规则 ID：${id}`, i + 1);
    const meta = parseMeta(metaText);
    const payload = [];
    let j = i + 1;
    let found = false;
    for (; j < lines.length; j++) {
      if (!fenced[j] && END_RE.test(lines[j])) {
        const end = lines[j].match(END_RE);
        if (end[1] !== id) throw new BlockError(`END 与 BEGIN 的 ID 不一致：${end[1]} ≠ ${id}`, j + 1);
        found = true;
        break;
      }
      if (!fenced[j] && BEGIN_RE.test(lines[j])) throw new BlockError(`块 ${id} 内嵌套了另一个 BEGIN`, j + 1);
      payload.push(lines[j]);
    }
    if (!found) throw new BlockError(`SHARED-RULE ${id} 缺少 END`, i + 1);
    const kind = meta.generated === '1' ? 'carrier' : 'owner';
    blocks.push({ id, version, meta, kind, payload: payload.join('\n'), line: i + 1, endLine: j + 1 });
    i = j;
  }
  return blocks;
}

/** 解析 REDLINES:v1 摘要块；不存在 ⇒ null。 */
export function parseRedlineBlock(text) {
  const lines = String(text).split('\n');
  const fenced = fencedLines(lines);
  let start = -1;
  for (let i = 0; i < lines.length; i++) {
    if (!fenced[i] && RED_BEGIN_RE.test(lines[i])) { start = i; break; }
  }
  if (start < 0) return null;
  for (let j = start + 1; j < lines.length; j++) {
    if (!fenced[j] && RED_END_RE.test(lines[j])) {
      return { payload: lines.slice(start + 1, j).join('\n'), line: start + 1, endLine: j + 1 };
    }
  }
  throw new BlockError('REDLINES:v1 缺少 END', start + 1);
}

/** `all` 或逗号分隔子集 ⇒ 去重后的角色数组；非法角色 ⇒ 抛。 */
export function expandCarriers(value) {
  const raw = String(value || '').trim();
  if (!raw) throw new Error('carriers= 为空');
  if (raw === 'none' || raw === '-') return [];
  const list = raw === 'all' ? [...ROLES] : raw.split(',').map((s) => s.trim()).filter(Boolean);
  const out = [];
  for (const r of list) {
    if (!ROLES.includes(r)) throw new Error(`carriers 含未知角色：${r}`);
    if (!out.includes(r)) out.push(r);
  }
  return out;
}

/** 规则 ID 的自然排序：先域，再数字（R-X-2 在 R-X-10 前）。 */
export function compareRuleIds(a, b) {
  const pa = a.match(/^R-([A-Z][A-Z0-9]*)-(\d+)$/);
  const pb = b.match(/^R-([A-Z][A-Z0-9]*)-(\d+)$/);
  if (!pa || !pb) return a.localeCompare(b);
  return pa[1] === pb[1] ? Number(pa[2]) - Number(pb[2]) : pa[1].localeCompare(pb[1]);
}

export function sortRules(rules) {
  return [...rules].sort((a, b) => compareRuleIds(a.id, b.id));
}

export function carrierLabel(carriers) {
  const list = Array.isArray(carriers) ? carriers : [];
  return list.length === ROLES.length && ROLES.every((r) => list.includes(r)) ? 'all' : list.join(',');
}

function escapeCell(s) {
  return String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

/** 渲染一个 carrier 块。 */
export function renderCarrierBlock(rule) {
  return [
    `<!-- BEGIN SHARED-RULE:${rule.id} ${rule.version || 'v1'} generated=1 source=owner:${rule.owner} -->`,
    rule.payload,
    `<!-- END SHARED-RULE:${rule.id} -->`,
  ].join('\n');
}

/** 渲染 `## Shared rules (generated)` 整节（含标题与生成提示）。 */
export function renderGeneratedSection(blocks) {
  const lines = [GENERATED_HEADING, '', GENERATED_NOTE];
  if (blocks.length) {
    lines.push('');
    for (const b of blocks) lines.push(b, '');
  } else {
    lines.push('');
  }
  // 末尾保留一个空行：替换整节时它正好充当与下一个 `## ` 标题之间的分隔。
  return lines.join('\n');
}

/**
 * 替换/插入 `## Shared rules (generated)` 整节；其它内容逐字保留。
 * 插入点：REDLINES 结束标记之后；没有则文件末尾。
 */
export function replaceGeneratedSection(text, blocks) {
  const lines = String(text).split('\n');
  const section = renderGeneratedSection(blocks).split('\n');
  const start = lines.findIndex((l) => l.trim() === GENERATED_HEADING);
  if (start >= 0) {
    let end = lines.length;
    for (let i = start + 1; i < lines.length; i++) {
      if (/^##\s+/.test(lines[i])) { end = i; break; }
    }
    const before = lines.slice(0, start);
    const after = lines.slice(end);
    return [...before, ...section, ...after].join('\n');
  }
  // 插入在 owner 段之后（若有），否则 REDLINES 之后。
  const ownerStart = lines.findIndex((l) => l.trim() === '## Shared rules (owner)');
  if (ownerStart >= 0) {
    let ownerEnd = lines.length;
    for (let i = ownerStart + 1; i < lines.length; i++) {
      if (/^##\s+/.test(lines[i])) { ownerEnd = i; break; }
    }
    const blank = ownerEnd > 0 && lines[ownerEnd - 1] !== '' ? [''] : [];
    return [...lines.slice(0, ownerEnd), ...blank, ...section, ...lines.slice(ownerEnd)].join('\n');
  }
  const redEnd = lines.findIndex((l) => RED_END_RE.test(l));
  const at = redEnd >= 0 ? redEnd + 1 : lines.length;
  return [...lines.slice(0, at), '', ...section, ...lines.slice(at)].join('\n');
}

/** 规则标题：marker 的 `title=` 优先，否则取 payload 首行压缩。 */
export function titleOf(meta, payload) {
  if (meta && meta.title) return meta.title;
  const line = String(payload || '').split('\n').find((l) => l.trim() && !l.trim().startsWith('<!--'));
  if (!line) return '';
  // guide-canonical pointer: `> \`R-X-1\` — Title — \`path §N\`.`
  const pointer = line.match(/^>\s*`R-[^`]+`\s*—\s*(.+?)\s*—\s*`[^`]+`\.?\s*$/);
  if (pointer) return pointer[1].trim();
  // legacy pointer form kept for older blocks.
  const short = line.match(/—\s*(.+?);\s*normative body:/);
  if (short) return short[1].trim();
  return line.replace(/^[>\s#*`-]+/, '').replace(/\*\*/g, '').replace(/[.:。]+$/, '').slice(0, 100);
}

/**
 * 校验并规范化一个 owner 块；返回可直接用于 sync/check 的规则对象。
 * 抛 Error（调用方决定退出码/汇总方式）。
 */
export function normalizeOwnerBlock(role, block) {
  const { id } = block;
  const meta = block.meta || {};
  if (!RULE_ID_RE.test(id)) throw new Error(`${role}: 非法规则 ID ${id}`);
  if (!meta.owner) throw new Error(`${role}: ${id} 缺少 owner=`);
  if (meta.owner !== role) throw new Error(`${role}: ${id} 的 owner=${meta.owner} 与所在角色不一致`);
  if (!ROLES.includes(meta.owner)) throw new Error(`${role}: ${id} owner 非法`);
  if (!meta.carriers) throw new Error(`${role}: ${id} 缺少 carriers=`);
  const carriers = expandCarriers(meta.carriers);
  const canonical = meta.canonical || 'owner';
  if (!['owner', 'guide'].includes(canonical)) throw new Error(`${role}: ${id} canonical 非法：${canonical}`);
  const detail = meta.detail || '-';
  if (canonical === 'guide' && detail === '-') throw new Error(`${role}: ${id} canonical=guide 必须有 detail=`);
  const status = meta.status || 'active';
  if (!['active', 'retired'].includes(status)) throw new Error(`${role}: ${id} status 非法：${status}`);
  if (status === 'retired' && carriers.length) throw new Error(`${role}: ${id} retired 时 carriers 必须为 none/-`);
  let redline = '';
  if (meta.redline) {
    const nums = meta.redline.split(',').map((s) => s.trim()).filter(Boolean);
    for (const n of nums) {
      if (!/^\d+$/.test(n) || Number(n) < 1 || Number(n) > 16) throw new Error(`${role}: ${id} redline 项非法：${n}`);
    }
    redline = nums.join(',');
  }
  return {
    id, version: block.version || 'v1', owner: role, carriers, canonical, detail, status, redline,
    title: titleOf(meta, block.payload), payload: block.payload,
  };
}

/** 渲染 team/SHARED-RULES.md（无规则正文，只有元数据）。 */
export function renderIndex(rules) {
  const rows = sortRules(rules).map((r) => `| ${[
    `\`${r.id}\``,
    escapeCell(r.title),
    r.owner,
    carrierLabel(r.carriers),
    r.canonical,
    r.detail && r.detail !== '-' ? `\`${escapeCell(r.detail)}\`` : '-',
    r.redline || '-',
    r.status || 'active',
  ].join(' | ')} |`);
  return [
    '# SHARED-RULES.md — generated shared-rule index',
    '',
    '> Generated by `team/scripts/sync-shared-rules.mjs`. **Do not hand-edit.**',
    '> Maintenance-only: this file records ownership/sharing, not rule bodies.',
    '> The rule body lives in the owner role AGENTS.md (`canonical=owner`) or the named guide (`canonical=guide`).',
    '',
    '| Rule ID | Title | Owner | Carriers | Canonical | Detail | Redline | Status |',
    '|---|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

/** 读/写 JSON（带缩进与尾换行，保证 git 稳定）。 */
export function readJson(p, fallback) {
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fallback; }
}
export function writeJson(p, value) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, `${JSON.stringify(value, null, 2)}\n`);
}

/** 角色 AGENTS 路径（repo 或 live）。 */
export function roleAgentsPath(role, mode) {
  return mode.mode === 'repo'
    ? path.join(mode.repo, 'roles', role, 'AGENTS.md')
    : path.join(mode.home, `workspace-${role}`, 'AGENTS.md');
}

/** 把 marker 的 detail（repo 形态）解析到当前模式的绝对路径；`-` ⇒ null。 */
export function resolveDetailPath(detail, mode) {
  const raw = String(detail || '').trim();
  if (!raw || raw === '-') return null;
  const p = raw.split(/\s+§/)[0].trim();
  if (!p || /^the rules/.test(p)) return null;
  if (mode.mode === 'repo') return path.join(mode.repo, p);
  if (p.startsWith('team/')) return path.join(mode.team, p.slice('team/'.length));
  const m = p.match(/^roles\/([^/]+)\/(.*)$/);
  if (m) return path.join(mode.home, `workspace-${m[1]}`, m[2]);
  return path.join(mode.team, p);
}
